-- 2. ADVANCED PL/SQL PACKAGE SPECIFICATION

CREATE OR REPLACE PACKAGE PKG_BLOOD_DONATION AS
    -- Types
    TYPE SYS_REFCURSOR IS REF CURSOR;

    -- Procedures
    PROCEDURE SP_CHECK_ELIGIBILITY (
        p_session_id    IN VARCHAR2,
        p_health_score  IN NUMBER,
        p_answers_json  IN CLOB,
        p_eligible_flag OUT VARCHAR2,
        p_status_msg    OUT VARCHAR2
    );

    PROCEDURE SP_REGISTER_DONOR (
        p_name         IN VARCHAR2,
        p_email        IN VARCHAR2,
        p_phone        IN VARCHAR2,
        p_blood_group  IN VARCHAR2,
        p_district     IN VARCHAR2,
        p_donor_id     OUT NUMBER,
        p_status_msg   OUT VARCHAR2
    );

    PROCEDURE SP_GET_STATE_STATS (
        p_cursor OUT SYS_REFCURSOR
    );
END PKG_BLOOD_DONATION;
/

-- 3. ADVANCED PL/SQL PACKAGE BODY

CREATE OR REPLACE PACKAGE BODY PKG_BLOOD_DONATION AS

    -- Procedure: SP_CHECK_ELIGIBILITY
    PROCEDURE SP_CHECK_ELIGIBILITY (
        p_session_id    IN VARCHAR2,
        p_health_score  IN NUMBER,
        p_answers_json  IN CLOB,
        p_eligible_flag OUT VARCHAR2,
        p_status_msg    OUT VARCHAR2
    ) IS
    BEGIN
        IF p_health_score >= 80.0 THEN
            p_eligible_flag := 'Y';
        ELSE
            p_eligible_flag := 'N';
        END IF;

        INSERT INTO DONOR_QUIZ_LOGS (SESSION_ID, HEALTH_SCORE, ANSWERS_JSON, ELIGIBLE_FLAG)
        VALUES (p_session_id, p_health_score, p_answers_json, p_eligible_flag);

        COMMIT;
        p_status_msg := 'SUCCESS: Eligibility attempt logged into Oracle DB.';
    EXCEPTION
        WHEN OTHERS THEN
            p_status_msg := 'ERROR: ' || SQLERRM;
    END SP_CHECK_ELIGIBILITY;

    -- Procedure: SP_REGISTER_DONOR
    PROCEDURE SP_REGISTER_DONOR (
        p_name         IN VARCHAR2,
        p_email        IN VARCHAR2,
        p_phone        IN VARCHAR2,
        p_blood_group  IN VARCHAR2,
        p_district     IN VARCHAR2,
        p_donor_id     OUT NUMBER,
        p_status_msg   OUT VARCHAR2
    ) IS
    BEGIN
        INSERT INTO DONORS (FULL_NAME, EMAIL, PHONE, BLOOD_GROUP, DISTRICT)
        VALUES (p_name, p_email, p_phone, p_blood_group, p_district)
        RETURNING DONOR_ID INTO p_donor_id;

        COMMIT;
        p_status_msg := 'SUCCESS: Donor registered successfully in Oracle Database.';
    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            p_status_msg := 'ERROR: Donor email already exists.';
        WHEN OTHERS THEN
            p_status_msg := 'ERROR: ' || SQLERRM;
    END SP_REGISTER_DONOR;

    -- Procedure: SP_GET_STATE_STATS (Returns AP Statewide Metrics)
    PROCEDURE SP_GET_STATE_STATS (
        p_cursor OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN p_cursor FOR
            SELECT 
                95124 AS TOTAL_DONORS,
                240 AS TOTAL_CENTERS,
                9 AS UPCOMING_CAMPS,
                10044 AS CAMPS_ORGANISED
            FROM DUAL;
    END SP_GET_STATE_STATS;

END PKG_BLOOD_DONATION;
