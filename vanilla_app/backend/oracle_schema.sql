-- 1. TABLES DEFINITION

CREATE TABLE DONORS (
    DONOR_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    PHONE VARCHAR2(15) NOT NULL,
    BLOOD_GROUP VARCHAR2(5) NOT NULL,
    DISTRICT VARCHAR2(50) NOT NULL,
    WEIGHT_KG NUMBER(5,2),
    AGE NUMBER(3),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE DONOR_QUIZ_LOGS (
    LOG_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SESSION_ID VARCHAR2(50),
    HEALTH_SCORE NUMBER(5,2) NOT NULL,
    ANSWERS_JSON CLOB,
    ELIGIBLE_FLAG CHAR(1) DEFAULT 'Y',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE BLOOD_CENTERS (
    CENTER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CENTER_NAME VARCHAR2(150) NOT NULL,
    DISTRICT VARCHAR2(50) NOT NULL,
    CONTACT_NO VARCHAR2(20),
    STATUS VARCHAR2(20) DEFAULT 'OPERATIONAL'
);

CREATE TABLE BLOOD_CAMPS (
    CAMP_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CAMP_NAME VARCHAR2(150) NOT NULL,
    DISTRICT VARCHAR2(50) NOT NULL,
    EVENT_DATE DATE NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'UPCOMING' -- UPCOMING, COMPLETED
);

